"use client";

// Strip above the UAV cards: district, UAVs flying now, simulated weather.

import { Chip } from "@/components/ui";
import { BATTERY } from "@/lib/config";
import type { Fleet } from "@/lib/types";

export function WeatherChip({ weather }: { weather: Fleet["weather"] }) {
  const wind = `${Math.round(weather.wind_mps)} m/s`;
  const gust = weather.gust_mps > weather.wind_mps ? ` (gusts ${Math.round(weather.gust_mps)})` : "";
  return (
    <Chip
      color={weather.flyable ? BATTERY.colors.ok : BATTERY.colors.critical}
      title={weather.flyable ? "Weather allows flights" : "Weather blocks flights"}
    >
      Wind {wind}
      {gust} · {weather.rain ? "Rain" : "Dry"}
      {!weather.flyable && " · No-fly"}
    </Chip>
  );
}

export default function FleetHeader({ fleet }: { fleet: Fleet }) {
  const flying = fleet.drones.filter((d) => d.status === "flying").length;
  return (
    <div className="flex min-w-0 flex-wrap items-center gap-2">
      <h1 className="mr-2 truncate text-lg font-semibold text-slate-900">{fleet.district.name}</h1>
      <Chip color={flying > 0 ? BATTERY.colors.ok : undefined}>{flying} flying now</Chip>
      <WeatherChip weather={fleet.weather} />
      {fleet.weather.simulated && <Chip title="The weather is generated by the backend, not a real feed">Simulated</Chip>}
    </div>
  );
}
